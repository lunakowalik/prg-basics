max_number = max(7,5,6,3,8,2)
print('Max number of 7,5,6,3,8,2 is', max_number)

min_number = min(4,7,2,3,9,8)
print('Min number of 4,7,2,3,9,8 is', min_number)

str_length = len("computer science")
print('The number of characters in "computer science" is', str_length)

letter_read = input("Letter: ")[0]
print('Letter read from the keyboard is', letter_read)

num = int("20303")
print('The number representing the string "20303" is', num)

binary = bin(304)
print('Binary string representing decimal number 304 is', binary)

hexadecimal = hex(304)
print('Hexadecimal string representing decimal number 304 is', hexadecimal)

euro_int = ord("€")
print('Integer representing the Unicode code of the € sign is', euro_int)

absolute = abs(-17)
print('Absolute value of -17 is', absolute)